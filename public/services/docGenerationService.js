function _tableRow(label, value) {
    return new TableRow({
        children: [
            new TableCell({ width: { size: 3000, type: WidthType.DXA }, children: [new Paragraph(label)] }),
            new TableCell({ width: { size: 7000, type: WidthType.DXA }, children: [new Paragraph(value ?? '')] }),
        ]
    });
}

function _tableRowChildren(label, children) {
    return new TableRow({
        children: [
            new TableCell({ width: { size: 3000, type: WidthType.DXA }, children: [new Paragraph(label)] }),
            new TableCell({ width: { size: 7000, type: WidthType.DXA }, children }),
        ]
    });
}

async function generateRequirementsDocument(projectID, requirements) {
    try {
        const projectName = await projectDB.fetchProjectName(projectID);

        const content = [
            new Paragraph({ children: [new TextRun({ text: projectName, size: 32, bold: true })] }),
            new Paragraph({ children: [new TextRun({ text: "Project Requirements Report", size: 24 })] }),
            new Paragraph(`Generated by Singularity AI: ${new Date().toLocaleString()}`),
            new Paragraph(""),
        ];

        const functional = requirements.filter(r => r.details?.requirementType === 'functional');
        const nonFunctional = requirements.filter(r => r.details?.requirementType === 'non-functional');

        content.push(new Paragraph(`Functional Requirements (${functional.length})`));
        for (const req of functional) {
            content.push(await createRequirementTable(req.details, projectID));
            content.push(new Paragraph(""));
        }

        content.push(new Paragraph(`Non-functional Requirements (${nonFunctional.length})`));
        for (const req of nonFunctional) {
            content.push(await createRequirementTable(req.details, projectID));
            content.push(new Paragraph(""));
        }

        const buffer = await Packer.toBuffer(new Document({ sections: [{ properties: {}, children: content }] }));
        await fss.saveGeneratedReport(projectID, buffer, fss.FSS_REPORT_REQUIREMENTS);

        serverLogger.info(`[${SERVICE_NAME}] Requirements report created for project: ${projectID}`);
        return true;

    } catch (err) {
        if (err instanceof ServiceError) throw err;
        throw new ServiceError(SERVICE_NAME, 'generateRequirementsDocument', 'Failed to generate requirements document', err);
    }
}

