// PDF conversion using libre-office or a pure JS solution
// For now, we'll use a simple approach - generate PDF using pdfkit for basic reports
// or fall back to DOCX if PDF generation is not available
async function convertDocxToPdf(docxBuffer) {
    // Try to use docx-pdf or similar library
    // For now, we'll create a simple PDF from scratch using pdfkit
    try {
        const PDFDocument = require('pdfkit');
        return new Promise((resolve, reject) => {
            const doc = new PDFDocument();
            const chunks = [];
            doc.on('data', chunk => chunks.push(chunk));
            doc.on('end', () => resolve(Buffer.concat(chunks)));
            doc.on('error', reject);
            doc.fontSize(16).text('Report', { align: 'center' });
            doc.moveDown();
            doc.fontSize(12).text('This report was generated by Singularity AI.', { align: 'center' });
            doc.moveDown();
            doc.fontSize(10).text('Note: Full PDF conversion from DOCX is not yet implemented. Please use DOCX format.', { align: 'center' });
            doc.end();
        });
    } catch (err) {
        throw new ServiceError(SERVICE_NAME, 'convertDocxToPdf', 'PDF generation is not available — use DOCX format', err);
    }
}

async function createRequirementTable(requirement, projectID) {
    try {
        const referencedDocsParagraphs = [];
        if (requirement.sourceReference?.length > 0) {
            for (const doc of requirement.sourceReference) {
                const metadata = await fss.getFileMetadata(doc.documentID, projectID);
                referencedDocsParagraphs.push(
                    new Paragraph({
                        text: `${metadata.documentName}${metadata.documentExt} (${doc.location})`,
                        bullet: { level: 0 }
                    })
                );
            }
        } else {
            referencedDocsParagraphs.push(new Paragraph("None"));
        }

        const referencedStoryParagraphs = [];
        if (requirement.referenceStory?.length > 0) {
            for (const story of requirement.referenceStory) {
                const info = await aiDB.getStoryTitle(story.storyID, projectID);
                referencedStoryParagraphs.push(
                    new Paragraph({
                        text: `Story ${info.storySeq} (${info.storyTitle})`,
                        bullet: { level: 0 }
                    })
                );
            }
        } else {
            referencedStoryParagraphs.push(new Paragraph("None"));
        }

        return new Table({
            width: { size: 100, type: WidthType.PERCENTAGE },
            layout: TableLayoutType.FIXED,
            rows: [
                _tableRow("Requirement Type", lodash.capitalize(requirement.requirementType)),
                _tableRow("Requirement Sequence", `${requirement.requirementSeq}`),
                _tableRow("Requirement Title", requirement.title),
                _tableRow("Requirement Description", requirement.description),
                _tableRow("Requirement Source", "Document"),
                _tableRowChildren("Referenced Documents", referencedDocsParagraphs),
                _tableRowChildren("Referenced Story", referencedStoryParagraphs),
            ]
        });
    } catch (err) {
        if (err instanceof ServiceError) throw err;
        throw new ServiceError(SERVICE_NAME, 'createRequirementTable', 'Failed to build requirement table', err);
    }
}

