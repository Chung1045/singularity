function createThreadEntry(threadEntry) {
    const agentMessage = normalizeAgentMarkdown(threadEntry.response?.message ?? "");
    return `\n**User**\n\n${threadEntry.message ?? ""}\n\n**Agent**\n\n${agentMessage}\n`;
}

function normalizeAgentMarkdown(md) {
    if (typeof md !== 'string') return '';
    return md
        .replace(/^### /gm, "##### ")
        .replace(/^## /gm, "#### ")
        .replace(/^# /gm, "### ");
}

function generateChatThreadHistDoc(projectID, chatID) {
    const stream = new PassThrough();

    // Start the async work but don't await it
    (async () => {
        try {
            const { convertMarkdownToDocx } = await import("@mohtasham/md-to-docx");
            const projectName = await projectDB.fetchProjectName(projectID);
            const chatThread = await aiDB.fetchChatThread(projectID, chatID);
            const chatThreadName = await aiDB.getChatThreadName(projectID, chatID);

            let markdown = `# ${projectName}\n\n## ${chatThreadName} – Chat Thread History\n\n`;

            if (chatThread?.conversations) {
                for (const thread of chatThread.conversations) {
                    markdown += createThreadEntry(thread);
                    markdown += `\n---\n`;
                }
            }

            const blob = await convertMarkdownToDocx(markdown);
            const buffer = Buffer.from(await blob.arrayBuffer());
            stream.write(buffer);
            stream.end();

        } catch (err) {
            serverLogger.error(`[${SERVICE_NAME}:generateChatThreadHistDoc] Failed: ${err.message}`);
            stream.destroy(new ServiceError(SERVICE_NAME, 'generateChatThreadHistDoc', 'Failed to generate chat thread document', err));
        }
    })();

    return stream;
}

